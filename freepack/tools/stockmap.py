#!/usr/bin/env python3
"""Write build/stockmap.toml: for each stock name a track can borrow, the
free file that stands in for it. The engine's free loader reads this.

[model]  stock model stem -> glTF (kind: made for it, "generic" crate stand-in)
[eco]    stock eco species -> glTF card tree
[sky]    stock .cub name   -> six PNG faces (face order as in sky.rs)
Names are lower case; look them up case-insensitively."""
import os, glob, tomllib
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); B = os.path.join(HERE, "build")
L = ["# Generated by tools/stockmap.py. Paths are relative to this file.", "", "[model]"]
missing = []
for line in open(os.path.join(B, "objects", "built.txt")):
    n, k = line.split()
    if k == "missing": missing.append(n); continue
    L.append(f'{n} = {{ file = "objects/{n}.glb", kind = "{k}" }}')
L += ["", "[eco]"]
for p in sorted(glob.glob(os.path.join(B, "eco", "*.glb"))):
    n = os.path.basename(p)[:-4]; L.append(f'{n} = "eco/{n}.glb"')
L += ["", "[sky]"]
src = tomllib.load(open(os.path.join(HERE, "sources.toml"), "rb"))
for n in src["sky"]:
    s = n.lower(); L.append(f'"{s}.cub" = [' + ", ".join(f'"skies/sky-{s}-{i}.png"' for i in range(6)) + "]")
L += ["", "# Stock models with no stand-in yet (large buildings, vehicles, stadium shells):",
      "missing = [" + ", ".join(f'"{m}"' for m in missing) + "]"]
open(os.path.join(B, "stockmap.toml"), "w").write("\n".join(L) + "\n")
print("model", sum(1 for l in L if l.startswith(tuple("abcdefghijklmnopqrstuvwxyz0123456789")) and "objects/" in l), "missing", len(missing))
